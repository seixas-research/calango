std::vector<std::vector<int>>
ThermodynamicIntegrationScriptGenerator::splitWindows(int windows, int jobs)
{
    std::vector<std::vector<int>> slices;
    if (windows <= 0)
        return slices;
    jobs = std::clamp(jobs, 1, windows);
    // Remainder spread over the leading slices, so no job carries two more
    // windows than another. With 12 windows over 5 jobs that is 3/3/2/2/2, not
    // 2/2/2/2/4 — the wall time of the whole run is the SLOWEST job, so an
    // uneven split is a slower run for no reason.
    const int base = windows / jobs;
    const int extra = windows % jobs;
    int next = 0;
    for (int job = 0; job < jobs; ++job) {
        const int count = base + (job < extra ? 1 : 0);
        std::vector<int> slice;
        slice.reserve(static_cast<std::size_t>(count));
        for (int i = 0; i < count; ++i)
            slice.push_back(next++);
        slices.push_back(std::move(slice));
    }
    return slices;
}

