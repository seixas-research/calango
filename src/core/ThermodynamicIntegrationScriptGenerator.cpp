/// Numbers that must SURVIVE THE ROUND TRIP, written with std::to_chars.
///
/// `ostringstream << double` writes six significant digits, and for the λ nodes
/// that is not a cosmetic loss: Gauss-Legendre weights are only valid on the
/// Gauss-Legendre nodes, and the reader checks that the λ values it got back
/// ARE those nodes before using them. A six-digit node misses the exact one by
/// ~1e-9, the check fails, and the run is silently re-integrated with a
/// trapezoid on a grid that was chosen for Gauss — a real accuracy loss with
/// nothing in the output pointing at the cause. to_chars writes the shortest
/// text that reads back as the identical double, which makes the round trip
/// exact by construction.
///
/// It is also the locale-safe spelling, which on this project's own
/// development machine (pt_BR, decimal comma) is not academic.
std::string number(double value)
{
    return localeSafeFormat(value);
}

std::string pythonList(const std::vector<double>& values)
{
    std::ostringstream out;
    out << "[";
    for (std::size_t i = 0; i < values.size(); ++i)
        out << (i ? ", " : "") << number(values[i]);
    out << "]";
    return out.str();
}

std::string pythonList(const std::vector<int>& values)
{
    std::ostringstream out;
    out << "[";
    for (std::size_t i = 0; i < values.size(); ++i)
        out << (i ? ", " : "") << values[i];
    out << "]";
    return out.str();
}

