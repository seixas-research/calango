std::string num(double v)
{
    return localeSafeFormat(v);
}

std::string pyStr(const std::string& s)
{
    return "\"" + s + "\"";
}

/// Literal `ase.Atoms(...)` construction for one structure, so the script
/// needs no staged structure file for any of the N + N(N-1) supercells —
/// the same "precompute the geometry in C++, bake it into the script"
/// idiom ElasticScriptGenerator uses for its strain matrices.
std::string atomsLiteral(const Structure& s)
{
    std::ostringstream out;
    out << "Atoms(symbols=[";
    bool first = true;
    for (const Atom& atom : s.atoms()) {
        if (!first)
            out << ", ";
        first = false;
        out << "\"" << atom.symbol() << "\"";
    }
    out << "], positions=[";
    first = true;
    for (const Atom& atom : s.atoms()) {
        if (!first)
            out << ", ";
        first = false;
        out << "[" << num(atom.position.x) << ", " << num(atom.position.y) << ", "
            << num(atom.position.z) << "]";
    }
    out << "], cell=[";
    const auto& v = s.cell().vectors();
    for (int i = 0; i < 3; ++i) {
        out << "[" << num(v[i].x) << ", " << num(v[i].y) << ", " << num(v[i].z) << "]";
        if (i < 2)
            out << ", ";
    }
    out << "], pbc=True)";
    return out.str();
}

std::string pristineLabel(const std::string& species)
{
    return "pristine_" + species;
}

std::string impurityLabel(const std::string& solute, const std::string& host)
{
    return solute + "_in_" + host;
}

