std::string generateDsimMultiPhaseScript(const DsimMultiPhaseConfig& c)
{
    std::ostringstream out;

    const std::string pA_a = phaseLabel(pristineLabel(c.speciesA), c.phaseA.phaseLabel);
    const std::string pA_b = phaseLabel(pristineLabel(c.speciesB), c.phaseA.phaseLabel);
    const std::string pA_bInA = phaseLabel(impurityLabel(c.speciesB, c.speciesA), c.phaseA.phaseLabel);
    const std::string pA_aInB = phaseLabel(impurityLabel(c.speciesA, c.speciesB), c.phaseA.phaseLabel);
    const std::string pB_a = phaseLabel(pristineLabel(c.speciesA), c.phaseB.phaseLabel);
    const std::string pB_b = phaseLabel(pristineLabel(c.speciesB), c.phaseB.phaseLabel);
    const std::string pB_bInA = phaseLabel(impurityLabel(c.speciesB, c.speciesA), c.phaseB.phaseLabel);
    const std::string pB_aInB = phaseLabel(impurityLabel(c.speciesA, c.speciesB), c.phaseB.phaseLabel);

    out << "#!/usr/bin/env python3\n"
        << "# Generated by Calango " << CALANGO_VERSION << " — multi-phase Dilute Solution\n"
        << "# Interpolation (DSI) model for " << c.speciesA << "(" << c.phaseA.phaseLabel << ")-"
        << c.speciesB << "(" << c.phaseB.phaseLabel << ").\n"
           "#\n"
           "# Two independent DSIM binary branches, one per phase, EACH an\n"
           "# ordinary Eq. 7 solve on its own crystal-structure template (four\n"
           "# supercells apiece, eight total); the two raw curves (each zero\n"
           "# at both its own endpoints by construction) are then shifted onto\n"
           "# one common, directly-comparable energy reference by the lattice-\n"
           "# stability correction below — see core/Dsim.hpp's \"Multi-phase\n"
           "# alloys\" note / docs/sphinx/source/simulations/dsim.md. Every\n"
           "# formula is reimplemented here rather than imported: this is a\n"
           "# plain ASE script, edit it freely or run it standalone.\n"
           "\n"
           "import json\n"
           "\n"
           "from ase import Atoms\n"
        << "from ase.optimize import " << toString(c.calculator.optimizer) << "\n";
    AseScriptGenerator::emitCellFilterImport(out, c.calculator.cellFilter);
    out << "\n" << AseScriptGenerator::jsonLoggerPreamble();

    out << "def attach_calculator(atoms):\n"
           "    \"\"\"Bind a fresh calculator to one configuration.\"\"\"\n";
    AseScriptGenerator::emitIndented(out, AseScriptGenerator::calculatorSnippet(c.calculator), "    ");
    out << "    return atoms\n"
           "\n\n";

    const int supercellAtomCount = c.phaseA.pristineA.size();
    out << "SPECIES_A = " << pyStr(c.speciesA) << "\n"
        << "SPECIES_B = " << pyStr(c.speciesB) << "\n"
        << "PHASE_A_LABEL = " << pyStr(c.phaseA.phaseLabel) << "\n"
        << "PHASE_B_LABEL = " << pyStr(c.phaseB.phaseLabel) << "\n"
        << "SUPERCELL_ATOM_COUNT = " << supercellAtomCount << "\n"
           "DILUTION = 1.0 / SUPERCELL_ATOM_COUNT\n"
        << "FMAX = " << num(c.calculator.fmax) << "\n"
        << "MAX_STEPS = " << c.calculator.maxSteps << "\n"
           "\n"
           "# All eight supercells this run needs: two ordinary 4-supercell\n"
           "# DSIM binary sets (pristine A, pristine B, B-in-A, A-in-B), one\n"
           "# built on each phase's own crystal-structure template. Species B\n"
           "# on phase A's template (and species A on phase B's) is a\n"
           "# single-element structure relabeled from the OTHER phase's own\n"
           "# input geometry, not yet relaxed to its own equilibrium volume —\n"
           "# that is exactly what the relax loop below is for.\n"
           "LABELS = [\n"
        << "    " << pyStr(pA_a) << ", " << pyStr(pA_b) << ", " << pyStr(pA_bInA) << ", "
        << pyStr(pA_aInB) << ",\n"
        << "    " << pyStr(pB_a) << ", " << pyStr(pB_b) << ", " << pyStr(pB_bInA) << ", "
        << pyStr(pB_aInB) << ",\n"
           "]\n"
           "STRUCTURES = [\n"
        << "    " << atomsLiteral(c.phaseA.pristineA) << ",  # " << c.speciesA << " on "
        << c.phaseA.phaseLabel << "\n"
        << "    " << atomsLiteral(c.phaseA.pristineB) << ",  # " << c.speciesB << " on "
        << c.phaseA.phaseLabel << "\n"
        << "    " << atomsLiteral(c.phaseA.impurityBInA) << ",  # " << c.speciesB << " diluted in "
        << c.speciesA << " (" << c.phaseA.phaseLabel << ")\n"
        << "    " << atomsLiteral(c.phaseA.impurityAInB) << ",  # " << c.speciesA << " diluted in "
        << c.speciesB << " on " << c.phaseA.phaseLabel << "\n"
        << "    " << atomsLiteral(c.phaseB.pristineA) << ",  # " << c.speciesA << " on "
        << c.phaseB.phaseLabel << "\n"
        << "    " << atomsLiteral(c.phaseB.pristineB) << ",  # " << c.speciesB << " on "
        << c.phaseB.phaseLabel << "\n"
        << "    " << atomsLiteral(c.phaseB.impurityBInA) << ",  # " << c.speciesB << " diluted in "
        << c.speciesA << " on " << c.phaseB.phaseLabel << "\n"
        << "    " << atomsLiteral(c.phaseB.impurityAInB) << ",  # " << c.speciesA << " diluted in "
        << c.speciesB << " (" << c.phaseB.phaseLabel << ")\n"
           "]\n"
           "\n"
           "def relax(atoms, tag):\n"
           "    \"\"\"Relax ions AND cell (the paper's protocol: force "
           "criterion\n"
           "    < 0.02 eV/A INCLUDING unit-cell relaxation), return\n"
           "    {'energy': eV, 'energy_per_atom': eV, 'steps': int,\n"
           "    'converged': bool}.\n"
           "    \"\"\"\n"
           "    attach_calculator(atoms)\n"
           "    try:\n"
           "        atoms.calc.set(directory=f'calc_{tag}')\n"
           "    except Exception:\n"
           "        pass\n";
    if (c.calculator.cellCustomMask) {
        out << "    target = _CellFilter(atoms, mask=[";
        for (int i = 0; i < 6; ++i)
            out << (c.calculator.cellMask[i] ? "1" : "0") << (i < 5 ? ", " : "");
        out << "])\n";
    } else {
        out << "    target = _CellFilter(atoms, hydrostatic_strain="
            << (c.calculator.cellHydrostatic ? "True" : "False") << ")\n";
    }
    out << "    opt = " << toString(c.calculator.optimizer)
        << "(target, logfile=f'relax_{tag}.log')\n"
           "    opt.run(fmax=FMAX, steps=MAX_STEPS)\n"
           "    energy = float(atoms.get_potential_energy())\n"
           "    converged = bool(abs(atoms.get_forces()).max() <= FMAX)\n"
           "    return {'energy': energy, 'energy_per_atom': energy / len(atoms),\n"
           "            'steps': int(opt.nsteps), 'converged': converged,\n"
           "            'natoms': len(atoms), 'volume': float(atoms.get_volume()),\n"
           "            'formula': atoms.get_chemical_formula()}\n"
           "\n"
           "\n"
           "records = {}\n"
           "failures = {}\n"
           "for step, (label, atoms) in enumerate(zip(LABELS, STRUCTURES)):\n"
           "    _calango_event('start', f'relaxing {label} "
           "({len(atoms)} atoms)')\n"
           "    try:\n"
           "        records[label] = relax(atoms, label)\n"
           "        print(f'CALANGO_CONFIG label={label} '\n"
           "              f'E={records[label][\"energy\"]:.6f} '\n"
           "              f'converged={records[label][\"converged\"]}',\n"
           "              flush=True)\n"
           "    except Exception as exc:\n"
           "        failures[label] = str(exc)\n"
           "        _calango_event('error', f'{label} FAILED: {exc}')\n"
           "        print(f'CALANGO_WARN {label} failed: {exc}', flush=True)\n"
           "    _calango_progress(step + 1, len(LABELS))\n"
           "\n"
           "# -- Analysis: two ordinary binary DSIM solves (Eq. 9-10 -> "
           "Eq. 7),\n"
           "# ------- one per phase, only meaningful once every supercell "
           "relaxed.\n"
           "EPSILON = 1e-8\n"
           "EV_TO_KJ_PER_MOL = 96.485332\n"
           "RESOLUTION = 100\n"
           "multi_phase = None\n"
           "if not failures:\n"
        << "    phase_a = None\n";
    emitPhaseBranchAnalysis(out, "phase_a", pA_a, pA_b, pA_bInA, pA_aInB);
    out << "    phase_b = None\n";
    emitPhaseBranchAnalysis(out, "phase_b", pB_a, pB_b, pB_bInA, pB_aInB);
    out << "\n"
           "    # Lattice-stability shift (core::applyLatticeStabilityShift):\n"
           "    # phase A is native to species A (no shift at x=0); its x=1\n"
           "    # shift is species B's OWN energy on phase A's template minus\n"
           "    # on phase B's template, per atom -- i.e. species B's lattice\n"
           "    # stability. Phase B is symmetric (native to species B, shift\n"
           "    # at x=0 only).\n"
           "    shift_a = {\n"
           "        'atX0Ev': 0.0,\n"
           "        'atX1Ev': (phase_a['pristine_b_eV'] - phase_b['pristine_b_eV']) / "
           "SUPERCELL_ATOM_COUNT,\n"
           "    }\n"
           "    shift_b = {\n"
           "        'atX0Ev': (phase_b['pristine_a_eV'] - phase_a['pristine_a_eV']) / "
           "SUPERCELL_ATOM_COUNT,\n"
           "        'atX1Ev': 0.0,\n"
           "    }\n"
           "\n"
           "    def apply_shift(raw, shift):\n"
           "        x_grid = raw['x_grid']\n"
           "        h_ev = [h + (1.0 - x) * shift['atX0Ev'] + x * shift['atX1Ev']\n"
           "                for x, h in zip(x_grid, raw['enthalpy_eV_per_atom'])]\n"
           "        return {\n"
           "            'x_grid': x_grid,\n"
           "            'enthalpy_eV_per_atom': h_ev,\n"
           "            'enthalpy_kJ_per_mol': [h * EV_TO_KJ_PER_MOL for h in h_ev],\n"
           "            # A linear-in-x shift moves endpoint values, not the\n"
           "            # tangent-line slopes at either end.\n"
           "            'dHdx_at_0_eV': raw['dHdx_at_0_eV'], 'dHdx_at_1_eV': "
           "raw['dHdx_at_1_eV'],\n"
           "        }\n"
           "\n"
           "    multi_phase = {\n"
           "        'phase_a': {\n"
           "            'label': PHASE_A_LABEL,\n"
           "            'energy_matrix': phase_a['energy_matrix'],\n"
           "            'm_matrix': phase_a['m_matrix'],\n"
           "            'raw': phase_a['raw'],\n"
           "            'shift_at_x0_eV': shift_a['atX0Ev'], 'shift_at_x1_eV': shift_a['atX1Ev'],\n"
           "            'corrected': apply_shift(phase_a['raw'], shift_a),\n"
           "        },\n"
           "        'phase_b': {\n"
           "            'label': PHASE_B_LABEL,\n"
           "            'energy_matrix': phase_b['energy_matrix'],\n"
           "            'm_matrix': phase_b['m_matrix'],\n"
           "            'raw': phase_b['raw'],\n"
           "            'shift_at_x0_eV': shift_b['atX0Ev'], 'shift_at_x1_eV': shift_b['atX1Ev'],\n"
           "            'corrected': apply_shift(phase_b['raw'], shift_b),\n"
           "        },\n"
           "    }\n"
           "    print('CALANGO_INFO multi-phase M matrices computed for "
           "'\n"
           "          f'{PHASE_A_LABEL}/{PHASE_B_LABEL}', flush=True)\n"
           "else:\n"
           "    print(f'CALANGO_WARN {len(failures)}/{len(LABELS)} supercell(s) "
           "failed — '\n"
           "          'DeltaH_mix cannot be evaluated', flush=True)\n"
           "\n"
           "summary = {\n"
           "    'schema': 'calango.dsim/3',\n"
           "    'species': [SPECIES_A, SPECIES_B],\n"
           "    'species_a': SPECIES_A, 'species_b': SPECIES_B,\n"
           "    'phase_a_label': PHASE_A_LABEL, 'phase_b_label': PHASE_B_LABEL,\n"
           "    'supercell_atom_count': SUPERCELL_ATOM_COUNT,\n"
           "    'dilution': DILUTION,\n"
        << "    'optimizer': " << pyStr(toString(c.calculator.optimizer)) << ",\n"
           "    'fmax_eV_per_A': FMAX,\n"
           "    'records': records,\n"
           "    'failures': failures,\n"
           "    'multi_phase': multi_phase,\n"
           "}\n"
           "with open('dsim.json', 'w') as handle:\n"
           "    json.dump(summary, handle, indent=2)\n"
           "\n"
           "print(f'CALANGO_RESULT dsim=dsim.json '\n"
           "      f'relaxed={len(records)}/{len(LABELS)} '\n"
           "      f'dHmix_available={multi_phase is not None}', flush=True)\n";

    return out.str();
}

