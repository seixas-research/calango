#include "core/WorkfunctionScriptGenerator.hpp"

#include "core/AseScriptGenerator.hpp"

#include <sstream>

namespace calango::core {

std::string generateWorkfunctionScript(const WorkfunctionConfig& cfg)
{
    // A wizard bug (or a hand-built config) must not become a script that
    // averages over a non-existent axis or measures the plateau over nothing:
    // clamp to the documented ranges rather than emitting broken Python.
    const int axis = (cfg.vacuumAxis >= 0 && cfg.vacuumAxis <= 2)
        ? cfg.vacuumAxis
        : 2;
    const double fraction =
        (cfg.plateauFraction > 0.0 && cfg.plateauFraction <= 0.45)
        ? cfg.plateauFraction
        : 0.15;

    std::ostringstream out;
    out << "# 2D work function (planar-averaged electrostatic potential) — "
           "generated by Calango\n"
           "import json\n"
           "\n"
           "import numpy as np\n"
           "\n"
        << AseScriptGenerator::jsonLoggerPreamble()
        << "_calango_progress(0, 4)\n"
           "\n"
           "# --- Baseline ground state (inherited, NOT re-converged) "
           "---------\n"
           "# The work function is a property of a specific converged SCF\n"
           "# solution — its electrostatic potential and its Fermi level. The\n"
           "# SCF was done by the Single-Point Calculation this run inherits\n"
           "# from; nothing here is computed self-consistently.\n"
           "from gpaw import GPAW\n"
           "\n"
        << "calc = GPAW(r\"" << cfg.baselineDensityPath << "\", txt=None)\n"
           "# The geometry comes from the .gpw itself, not from the staged\n"
           "# structure file: the potential grid belongs to the baseline's\n"
           "# cell, and a workspace structure edited since the SCF would put\n"
           "# the vacuum bookkeeping below on the wrong geometry.\n"
           "atoms = calc.get_atoms()\n"
           "efermi = float(calc.get_fermi_level())\n"
           "_calango_progress(1, 4)\n"
           "\n"
           "# --- Planar-averaged electrostatic potential "
           "---------------------\n"
           "# get_electrostatic_potential() interpolates the total Kohn-Sham\n"
           "# electrostatic potential (Hartree + external, NOT xc) onto the\n"
           "# fine real-space grid, already in eV. Averaging over the two\n"
           "# in-plane axes leaves V(z): oscillating through the atomic planes\n"
           "# inside the slab, and flattening in the vacuum to the constant\n"
           "# the work function is measured against.\n"
        << "vacuum_axis = " << axis << "\n"
           "pot = np.asarray(calc.get_electrostatic_potential(), dtype=float)\n"
           "in_plane = tuple(i for i in range(3) if i != vacuum_axis)\n"
           "v_planar = pot.mean(axis=in_plane)\n"
           "n_z = int(len(v_planar))\n"
           "L_z = float(atoms.cell.lengths()[vacuum_axis])\n"
           "dz = L_z / n_z  # periodic grid: n_z points cover [0, L_z)\n"
           "z_A = np.arange(n_z) * dz\n"
           "_calango_progress(2, 4)\n"
           "\n"
           "# --- The vacuum gap and its edge plateaus ------------------------\n"
           "# The atoms occupy [z_lo, z_hi] along the vacuum axis; the gap is\n"
           "# the remainder, which WRAPS through the cell boundary — from the\n"
           "# topmost atom up to one edge and on from the other edge down to\n"
           "# the lowest atom. The vacuum levels are therefore read AT THE\n"
           "# CELL EDGES: each edge is the point of the gap farthest from both\n"
           "# surfaces, where the potential has had the whole half-gap to\n"
           "# reach its asymptote.\n"
           "spos = atoms.get_scaled_positions(wrap=True)[:, vacuum_axis]\n"
           "z_lo = float(spos.min()) * L_z\n"
           "z_hi = float(spos.max()) * L_z\n"
           "gap_A = (L_z - z_hi) + z_lo\n"
           "if gap_A < 4.0:\n"
           "    print(\"CALANGO_WARN the vacuum gap along axis \"\n"
           "          f\"{vacuum_axis} is only {gap_A:.2f} Å. Either the cell \"\n"
           "          \"has almost no vacuum, or the slab crosses the periodic \"\n"
           "          \"boundary — then the cell edges sample the SLAB, not \"\n"
           "          \"its vacuum. Center the slab in the cell (vacuum split \"\n"
           "          \"at both edges) and re-run the baseline.\", flush=True)\n"
           "\n"
           "# --- Plateau flatness --------------------------------------------\n"
           "# |dV/dz| over the outermost fraction of the vacuum gap at each\n"
           "# cell edge — exactly where the vacuum levels are read. A converged\n"
           "# vacuum is FLAT there; a slope means the gap is too thin (the two\n"
           "# faces' potential tails still overlap where the level is read).\n"
           "# The WORST point in either window is reported, because one bad\n"
           "# face is enough to make its Φ untrustworthy.\n"
        << "plateau_fraction = " << fraction << "\n"
           "window_A = max(plateau_fraction * gap_A, 3.0 * dz)\n"
           "n_win = max(int(round(window_A / dz)), 2)\n"
           "dvdz = np.gradient(v_planar, dz)\n"
           "flat_low = float(np.max(np.abs(dvdz[:n_win])))\n"
           "flat_high = float(np.max(np.abs(dvdz[-n_win:])))\n"
           "plateau_flatness = max(flat_low, flat_high)\n"
           "print(f\"CALANGO_INFO vacuum_gap_A={gap_A:.2f} \"\n"
           "      f\"plateau_window_A={n_win * dz:.2f} \"\n"
           "      f\"flatness_eV_per_A={plateau_flatness:.5f}\", flush=True)\n"
           "if plateau_flatness > 0.005:\n"
           "    print(\"CALANGO_WARN the potential is not flat at the cell \"\n"
           "          f\"edges (|dV/dz| = {plateau_flatness:.4f} eV/Å): the \"\n"
           "          \"vacuum region is not converged — too thin for V(z) to \"\n"
           "          \"reach its asymptote. Rebuild the slab with more vacuum \"\n"
           "          \"and re-run the baseline.\", flush=True)\n"
           "_calango_progress(3, 4)\n"
           "\n"
           "# --- Vacuum levels and the work function -------------------------\n"
           "# One level PER FACE. With a dipole correction in the baseline the\n"
           "# potential may step across the correction plane, and the two\n"
           "# edges are genuinely different vacuum levels — an asymmetric slab\n"
           "# (an adsorbate on one side, a polar termination) has two work\n"
           "# functions. WITHOUT a dipole correction, periodic boundary\n"
           "# conditions force one continuous potential across the gap, so the\n"
           "# two edges share a single ARTIFICIAL average and the two Φ below\n"
           "# coincide by construction, not by physics. Both are reported\n"
           "# either way, so equality stays visible for what it is.\n"
           "v_vac_low = float(v_planar[0])\n"
           "v_vac_high = float(v_planar[-1])\n"
           "phi_low = v_vac_low - efermi\n"
           "phi_high = v_vac_high - efermi\n"
           "if abs(v_vac_low - v_vac_high) > 0.02:\n"
           "    print(f\"CALANGO_INFO the two faces differ: \"\n"
           "          f\"phi_low={phi_low:.4f} eV phi_high={phi_high:.4f} eV \"\n"
           "          f\"(dipole-corrected baseline)\", flush=True)\n"
           "\n"
           "results = {\n"
           "    \"vacuum_axis\": vacuum_axis,\n"
           "    \"z_A\": [float(v) for v in z_A],\n"
           "    \"v_planar_eV\": [float(v) for v in v_planar],\n"
           "    \"efermi_eV\": efermi,\n"
           "    \"vacuum_level_low_eV\": v_vac_low,\n"
           "    \"vacuum_level_high_eV\": v_vac_high,\n"
           "    \"workfunction_low_eV\": phi_low,\n"
           "    \"workfunction_high_eV\": phi_high,\n"
           "    \"plateau_flatness_eV_per_A\": plateau_flatness,\n"
           "}\n"
           "with open(\"workfunction.json\", \"w\") as handle:\n"
           "    json.dump(results, handle)\n"
           "_calango_progress(4, 4)\n"
           "print(f\"CALANGO_RESULT workfunction=workfunction.json \"\n"
           "      f\"phi_low_eV={phi_low:.4f} phi_high_eV={phi_high:.4f}\",\n"
           "      flush=True)\n";
    return out.str();
}

} // namespace calango::core
