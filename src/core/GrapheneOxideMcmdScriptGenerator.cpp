const char* goMcOptimizerName(GoMcOptimizer optimizer)
{
    // The ASE class name, written straight into the script. A switch with no
    // default: adding an optimizer to the enum must not silently fall through
    // to BFGS, it must stop compiling until this table names it too.
    switch (optimizer) {
    case GoMcOptimizer::Bfgs:
        return "BFGS";
    case GoMcOptimizer::Lbfgs:
        return "LBFGS";
    case GoMcOptimizer::Fire:
        return "FIRE";
    case GoMcOptimizer::Mdmin:
        return "MDMin";
    }
    return "BFGS";
}

