std::string generateGwScript(const GwConfig& config)
{
    std::ostringstream out;
    out << "#!/usr/bin/env python3\n"
           "# G0W0 quasiparticle corrections — generated by Calango "
        << CALANGO_VERSION << "\n"
           "#\n"
           "# The quasiparticle energy is\n"
           "#   E_qp(n,k) = e_DFT(n,k) + Z(n,k) [Sigma(n,k; e_DFT) - V_xc(n,k)]\n"
           "# i.e. the DFT eigenvalue with its exchange-correlation potential\n"
           "# replaced by the (energy-dependent, non-local) self-energy. It is a\n"
           "# ONE-SHOT correction: nothing here is self-consistent, and the\n"
           "# result is only meaningful relative to the baseline it corrects.\n"
           "import json\n"
           "\n"
           "import numpy as np\n"
           "\n"
        << AseScriptGenerator::jsonLoggerPreamble()
        << "_calango_log.progress(0, 4)\n"
           "\n";

    if (config.engine == GwEngine::Gpaw)
        emitGpawGw(out, config);
    else
        emitYamboGw(out, config);

    out << "\n"
           "# --- Summary ------------------------------------------------------\n"
        << "engine = \""
        << (config.engine == GwEngine::Gpaw ? "GPAW" : "Yambo") << "\"\n"
           "summary = {\n"
           "    \"engine\": engine,\n"
        << "    \"frequency_treatment\": \""
        << (config.frequency == GwFrequencyTreatment::PlasmonPole
                ? "plasmon-pole"
                : "real-axis")
        << "\",\n"
        << "    \"screening_cutoff_eV\": " << config.screeningCutoffEv << ",\n"
           "    \"dft_vbm_eV\": dft_vbm,\n"
           "    \"dft_cbm_eV\": dft_cbm,\n"
           "    \"dft_gap_eV\": dft_gap,\n"
           "    \"gw_vbm_eV\": gw_vbm,\n"
           "    \"gw_cbm_eV\": gw_cbm,\n"
           "    \"gw_gap_eV\": gw_gap,\n"
           "    # The headline number: how much the gap opens. GW typically\n"
           "    # widens a DFT gap by 0.5-2 eV, and a NEGATIVE renormalization\n"
           "    # is a strong hint the calculation is unconverged rather than a\n"
           "    # physical result.\n"
           "    \"gap_renormalization_eV\": (\n"
           "        None if None in (dft_gap, gw_gap) else gw_gap - dft_gap),\n"
           "    \"dft_eigenvalues_eV\": [[float(v) for v in row]\n"
           "                            for row in np.atleast_2d(dft.reshape("
           "-1, dft.shape[-1]))],\n"
           "    \"qp_eigenvalues_eV\": [[float(v) for v in row]\n"
           "                           for row in np.atleast_2d(qp.reshape("
           "-1, qp.shape[-1]))],\n"
           "}\n"
           "with open(\"gw.json\", \"w\") as handle:\n"
           "    json.dump(summary, handle)\n"
           "_calango_log.progress(4, 4)\n"
           "if summary[\"gap_renormalization_eV\"] is not None:\n"
           "    print(f\"CALANGO_RESULT dft_gap_eV={dft_gap:.4f} \"\n"
           "          f\"gw_gap_eV={gw_gap:.4f} \"\n"
           "          f\"renormalization_eV=\"\n"
           "          f\"{summary['gap_renormalization_eV']:.4f}\", flush=True)\n"
           "print(\"CALANGO_INFO wrote gw.json\", flush=True)\n"
           "print(\"CALANGO_DONE\", flush=True)\n";
    return out.str();
}

